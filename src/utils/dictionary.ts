export function translate(lang: Language, key: keyof typeof translations['en'], replace?: Record<string, string | number>): string {
  const dict = translations[lang] || translations['en'];
  let text = (dict[key] || translations['en'][key]) as string;
  if (replace) {
    Object.entries(replace).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}
